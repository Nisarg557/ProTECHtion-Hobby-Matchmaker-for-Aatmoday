/* =====================================================
   ENROL MODAL
===================================================== */

function openEnrolModal() {

    const modal =
        document.getElementById(
            "enrolModal"
        );


    const clubName =
        document.getElementById(
            "enrolClubName"
        );


    clubName.textContent =
        `You're enrolling for the ${club.name}.`;


    modal.classList.add("show");

}



/* =====================================================
   CLOSE MODAL
===================================================== */

function closeEnrolModal() {

    const modal =
        document.getElementById(
            "enrolModal"
        );


    modal.classList.remove(
        "show"
    );


    document.getElementById(
        "enrolSuccess"
    ).style.display =
        "none";


    document.getElementById(
        "enrolForm"
    ).style.display =
        "block";


    document.getElementById(
        "enrolForm"
    ).reset();

}



/* =====================================================
   SUBMIT ENROLMENT
===================================================== */

function submitEnrollment(event) {

    event.preventDefault();


    const name =
        document.getElementById(
            "studentName"
        ).value.trim();


    const email =
        document.getElementById(
            "studentEmail"
        ).value.trim();


    if (
        !name ||
        !email
    ) {

        alert(
            "Please fill in your name and email."
        );

        return;

    }


    /*
       FRONTEND DEMO

       For the hackathon prototype, we show a
       successful enrolment request.

       Later this can be connected to:
       - Firebase
       - MongoDB
       - Node.js
       - Google Forms
       - university API
    */


    document.getElementById(
        "enrolForm"
    ).style.display =
        "none";


    document.getElementById(
        "enrolSuccess"
    ).style.display =
        "block";

}
